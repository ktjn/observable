#!/usr/bin/env bash
set -euo pipefail

# render-pinned-compose.sh
#
# Renders distribution/compose.pinned.yaml: a Docker Compose override that pins
# every deployable component image to the version recorded in
# distribution/manifest.yaml. `observable-distribution` uses it to install a
# tested component set (docs/component-decomposition.md Phase 7 sub-step 5):
#
#   docker compose -f docker-compose.yml -f distribution/compose.pinned.yaml \
#     --profile verification up smoke-test --abort-on-container-exit
#
# Usage:
#   bash scripts/render-pinned-compose.sh           # write the override
#   bash scripts/render-pinned-compose.sh --check    # fail if it is out of date

REPO_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
MANIFEST="$REPO_ROOT/distribution/manifest.yaml"
OUT="$REPO_ROOT/distribution/compose.pinned.yaml"

EXPECTED=(contracts auth control ingest process storeClickhouse query alerting web)

fail() {
  echo "FAIL: $1" >&2
  exit 1
}

# manifest key -> "<compose service> <image repository>" (empty when the
# component has no runtime image).
component_compose() {
  case "$1" in
    contracts) echo "" ;;
    auth) echo "auth-service observable-auth" ;;
    control) echo "admin-service observable-control" ;;
    ingest) echo "ingest-gateway observable-ingest" ;;
    process) echo "stream-processor observable-process" ;;
    storeClickhouse) echo "storage-writer observable-store-clickhouse" ;;
    query) echo "query-api observable-query" ;;
    alerting) echo "alert-evaluator observable-alerting" ;;
    web) echo "frontend observable-web" ;;
  esac
}

[[ -f "$MANIFEST" ]] || fail "manifest not found: $MANIFEST"

declare -A versions=()
while IFS= read -r line; do
  key="$(sed -E 's/^[[:space:]]+//; s/:.*//' <<<"$line")"
  value="$(sed -E 's/^[^:]+:[[:space:]]*//' <<<"$line")"
  versions["$key"]="$value"
done < <(awk '/^components:/{f=1; next} f && /^[^[:space:]#]/{exit} f && /^  [A-Za-z]/{print}' "$MANIFEST")

render() {
  echo "# Generated by scripts/render-pinned-compose.sh from distribution/manifest.yaml."
  echo "# Do not edit by hand. This override pins every deployable component image to the"
  echo "# tested distribution version. Install the pinned set with:"
  echo "#   docker compose -f docker-compose.yml -f distribution/compose.pinned.yaml \\"
  echo "#     --profile verification up smoke-test --abort-on-container-exit"
  echo "services:"
  for component in "${EXPECTED[@]}"; do
    mapping="$(component_compose "$component")"
    [[ -n "$mapping" ]] || continue
    read -r service repo <<<"$mapping"
    version="${versions[$component]:-}"
    [[ -n "$version" ]] || fail "component '$component' missing from $MANIFEST"
    echo "  ${service}:"
    echo "    image: ${repo}:${version}"
  done
}

if [[ "${1:-}" == "--check" ]]; then
  tmp="$(mktemp)"
  render > "$tmp"
  if ! diff -u "$OUT" "$tmp" >/dev/null 2>&1; then
    echo "FAIL: distribution/compose.pinned.yaml is out of date with distribution/manifest.yaml" >&2
    diff -u "$OUT" "$tmp" >&2 || true
    rm -f "$tmp"
    exit 1
  fi
  rm -f "$tmp"
  echo "OK  pinned compose override matches the distribution manifest"
else
  render > "$OUT"
  echo "OK  wrote $OUT"
fi
